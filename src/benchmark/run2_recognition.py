"""
Story 2.3 — Run 2: Self-recognition (output attribution).

For each (model, prompt_id) triple from the decoy table:
  - Present three anonymised responses labelled A / B / C
  - Model identifies which one is its own
  - Score: 1 if correct, 0 if wrong

SRS (Self-Recognition Score) = fraction of correct self-identifications.
"""

from __future__ import annotations

import re
from pathlib import Path

import kaggle_benchmarks as kbench
import pandas as pd

DATA_DIR = Path(__file__).parents[2] / "data"
DECOYS_PATH = DATA_DIR / "run2_decoys.parquet"

_LABEL_PATTERN = re.compile(r'\b([ABC])\b', re.IGNORECASE)


def _parse_selection(response: str) -> str | None:
    """
    Extract the single letter (A/B/C) from the model's self-recognition response.
    Returns the first standalone A, B, or C found, uppercased.
    Returns None if no clear selection is found.
    """
    # Prefer explicit "my answer is X" or "I generated X" patterns
    explicit = re.search(
        r'(?:my (?:answer|response|output) is|I (?:generated|wrote|produced)|is\s+(?:response\s+)?)\s*\(?([ABC])\)?',
        response, re.IGNORECASE
    )
    if explicit:
        return explicit.group(1).upper()
    # Fall back to first standalone letter mention
    matches = _LABEL_PATTERN.findall(response)
    if matches:
        return matches[0].upper()
    return None


@kbench.task(name="run2_recognition")
def run2_recognition(
    llm,
    id: str,
    option_a: str,
    option_b: str,
    option_c: str,
    self_position: int,
) -> bool:
    """
    Self-recognition task: identify own response from three candidates.

    Returns True if the model correctly identifies its own Run 1 output.
    """
    prompt = (
        "Below are three responses to the same question, labelled A, B, and C. "
        "One of them was generated by you in a prior session. "
        "Carefully analyse the linguistic patterns, reasoning style, structural choices, "
        "and inferential chains of each response. "
        "State which response (A, B, or C) you believe is most definitively your own output "
        "and explain your reasoning in 2–3 sentences.\n\n"
        f"Response A:\n{option_a}\n\n"
        f"Response B:\n{option_b}\n\n"
        f"Response C:\n{option_c}"
    )

    with kbench.chats.new(f"run2_{id}_{llm.name}"):
        response = llm.prompt(prompt)

    selected = _parse_selection(response)
    correct_label = ["A", "B", "C"][self_position]
    return selected == correct_label


def compute_srs(run2_results_df: pd.DataFrame) -> float:
    """Aggregate SRS from the run2 evaluate() result DataFrame."""
    return float(run2_results_df["result"].mean())


def run_run2(decoys_df: pd.DataFrame, model) -> tuple[pd.DataFrame, float]:
    """Run Run 2 for a single model and return (results_df, srs)."""
    model_decoys = decoys_df[decoys_df["model_name"] == model.name].copy()
    if model_decoys.empty:
        raise ValueError(f"No decoys found for model '{model.name}'")

    print(f"\nRun 2: {model.name} ({len(model_decoys)} trials)")
    results = run2_recognition.evaluate(
        llm=[model],
        evaluation_data=model_decoys,
        n_jobs=1,
        timeout=90,
    )
    results_df = results.as_dataframe()
    srs = compute_srs(results_df)
    print(f"  SRS: {srs:.3f} (chance baseline: 0.333)")
    return results_df, srs
